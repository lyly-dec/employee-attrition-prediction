"""### Tính Tuyến tính của biến liên tục với Logit

"""

import statsmodels.api as sm
import pandas as pd
import numpy as np
from sklearn.linear_model import LogisticRegression

# Các biến cần kiểm tra
numeric_cols = ['satisfaction_level', 'last_evaluation', 'number_project',
                'average_monthly_hours', 'time_spend_company']
# Chạy Logistic Regression tạm để tính log-odds
lr_temp = LogisticRegression(max_iter=1000)
lr_temp.fit(X_train_processed[numeric_cols], y_train)
log_odds = lr_temp.predict_log_proba(X_train_processed[numeric_cols])[:, 1]
# Box-Tidwell Test
results = []
for col in numeric_cols:
    X_col = X_train_processed[col].values
    x_log = X_col * np.log(np.abs(X_col) + 1e-10)

    X_design = sm.add_constant(np.column_stack([X_col, x_log]))
    model = sm.OLS(log_odds, X_design)
    result = model.fit()
    results.append({
        'Biến': col,
        'Hệ số x·ln(x)': result.params[2],
        'P-value': result.pvalues[2]
    })
results_df = pd.DataFrame(results)
print(results_df)

